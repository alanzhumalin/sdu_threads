type MessageKey = keyof (typeof messages)["ru"];

type I18nValue = {
  language: AppLanguage;
  setLanguage: (next: AppLanguage) => void;
  t: (key: MessageKey) => string;
  pick: (text: { kk: string; ru: string; en: string }) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

const getInitialLanguage = (): AppLanguage => {
  if (typeof window === "undefined") return "kk";
  const saved = String(window.localStorage.getItem(STORAGE_KEY) || "").toLowerCase();
  if (saved === "kk" || saved === "ru" || saved === "en") return saved;
  return "kk";
};

export function I18nProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<AppLanguage>(() => getInitialLanguage());

  useEffect(() => {
    if (typeof window === "undefined") return;
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
    setClientLanguage(language);
  }, [language]);

  const value = useMemo<I18nValue>(() => {
    const t = (key: MessageKey) => {
      return messages[language][key] ?? messages.kk[key];
    };
    const pick = (text: { kk: string; ru: string; en: string }) => text[language] ?? text.kk;
    return { language, setLanguage, t, pick };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return ctx;
}
